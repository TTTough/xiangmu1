def main():
    text = MD.read_text(encoding="utf-8")
    bad = []
    for tag, desc, old, new, n in EDITS:
        cnt = text.count(old)
        if cnt != n:
            bad.append("[%s] %s —— 预期 %d 次，实际 %d 次" % (tag, desc, n, cnt))
            continue
        text = text.replace(old, new)
        print("[%s] %s" % (tag, desc))
    if bad:
        print("\n失败 %d 条：" % len(bad))
        for b in bad:
            print("  " + b)
        sys.exit(1)
    MD.write_text(text, encoding="utf-8")
    print("\n共 %d 条编辑全部命中，已写回 %s" % (len(EDITS), MD.name))


if __name__ == "__main__":
    main()
