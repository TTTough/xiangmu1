def main():
    text = MD.read_text(encoding="utf-8")
    problems = []
    for tag, desc, old, new, n in EDITS:
        cnt = text.count(old)
        if cnt != n:
            problems.append("[%s] %s —— 预期命中 %d 次，实际 %d 次" % (tag, desc, n, cnt))
            continue
        text = text.replace(old, new)
        print("[%s] %s" % (tag, desc))
    if "D10" not in text and False:
        pass
    if "--dry-run" in sys.argv:
        print("\n（dry-run，未写回文件）共 %d 条编辑，%d 条失败" % (len(EDITS), len(problems)))
    else:
        MD.write_text(text, encoding="utf-8")
        print("\n共 %d 条编辑，%d 条失败；已写回 %s" % (len(EDITS), len(problems), MD.name))
    if problems:
        print("\n失败清单：")
        for p in problems:
            print("  " + p)
        sys.exit(1)


if __name__ == "__main__":
    main()

